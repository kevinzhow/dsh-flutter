/// Line cap of an icon stroke (`strokeLinecap`).
enum DshIconCap { butt, round, square }

/// One path of an icon: SVG path data, filled or stroked with the icon colour.
class DshIconShape {
  const DshIconShape(
    this.path, {
    this.fill = false,
    this.cap = DshIconCap.butt,
    this.evenOdd = false,
    this.opacity = 1,
    this.cutWidth = 0,
  });

  final String path;
  final bool fill;
  final DshIconCap cap;
  final bool evenOdd;

  /// The element's `opacity` (the faint ring of the compact glyph).
  final double opacity;

  /// More than zero: not drawn but carved, a stroke of this width cleared out
  /// of the shapes before it (an SVG `mask` along a line, the archive-off
  /// slash). The shapes after it draw over the gap.
  final double cutWidth;
}

/// A dsh product icon: the path data of its SVG artwork (generated by
/// `tool/icons/gen_icons.py` from ui-primitives), drawn in `currentColor`.
class DshIconData {
  const DshIconData({
    required this.viewBox,
    required this.size,
    required this.strokeWidth,
    required this.shapes,
  });

  /// Edge of the square view box.
  final int viewBox;

  /// The glyph's own drawn size in logical px (dsh's default `size` prop).
  final int size;

  /// Stroke width in view box units.
  final double strokeWidth;

  final List<DshIconShape> shapes;
}
