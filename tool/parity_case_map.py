#!/usr/bin/env python3
"""Generate case_map.g.dart next to every `test/parity/cases/` directory.

Merges every public top-level `final Map<String, ParityCase> <name> = ...` and
`final Map<String, ParityUncovered> <name> = ...` declared in <package>/test/parity/cases/*.dart into
the two maps `parityCases` and `parityUncovered` that package's capture entry point reads. The harness
package tool/parity_flutter always has one; an app, feature or package that adds screens adds its own
test/parity/{parity_capture_test.dart,case_map.dart,cases/} (docs/parity.md). The generated file is
git-ignored: adding a case family means adding a cases file, never editing a shared one (parallel
branches do not conflict). A duplicate key is reported when the capture starts.

  tool/parity_case_map.py [--check]     --check: exit 1 if the generated file is missing or stale
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKIP = {'.dart_tool', 'build', 'node_modules', '.local'}
DECL = re.compile(r'^final\s+Map<String,\s*(ParityCase|ParityUncovered)>\s+([A-Za-z][A-Za-z0-9_]*)\s*=', re.M)


def collect(cases_dir):
    found = []
    for path in sorted(cases_dir.glob('*.dart')):
        for kind, name in DECL.findall(path.read_text()):
            if not name.startswith('_'):
                found.append((path, kind, name))
    return found


def render(found):
    imports, cases, uncovered = [], [], []
    for i, path in enumerate(sorted({p for p, _, _ in found})):
        alias = 'c%d' % i
        imports.append("import 'cases/%s' as %s;" % (path.name, alias))
        for p, kind, name in found:
            if p == path:
                (cases if kind == 'ParityCase' else uncovered).append('%s.%s' % (alias, name))
    lines = [
        '// GENERATED by tool/parity_case_map.py; do not edit, do not commit.',
        '// ignore_for_file: type=lint',
        "import 'package:dsh_parity/dsh_parity.dart';",
        *imports,
        '',
        'Map<String, T> _merge<T>(String what, List<Map<String, T>> maps) {',
        '  final out = <String, T>{};',
        '  for (final map in maps) {',
        '    for (final entry in map.entries) {',
        '      if (out.containsKey(entry.key)) {',
        "        throw StateError('duplicate parity $what key ${entry.key}');",
        '      }',
        '      out[entry.key] = entry.value;',
        '    }',
        '  }',
        '  return out;',
        '}',
        '',
        'final Map<String, ParityCase> parityCases = _merge("case", [%s]);' % ', '.join(cases),
        'final Map<String, ParityUncovered> parityUncovered = _merge("uncovered", [%s]);' % ', '.join(uncovered),
        '',
    ]
    return '\n'.join(lines)


def parity_dirs(root=ROOT):
    found = []
    for group in ('tool', 'apps', 'features', 'packages'):
        for cases in sorted((root / group).glob('*/test/parity/cases')):
            if not SKIP & set(cases.parts):
                found.append(cases.parent)
    return found


def generate(write=True, root=ROOT):
    """-> {path: text}; writes the files unless write is False."""
    out = {}
    for base in parity_dirs(root):
        out[base / 'case_map.g.dart'] = render(collect(base / 'cases'))
    if write:
        for path, text in out.items():
            if not path.exists() or path.read_text() != text:
                path.write_text(text)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    texts = generate(write=not args.check)
    stale = [p for p, t in texts.items() if not p.exists() or p.read_text() != t]
    for path in stale:
        print('%s is missing or stale; run tool/parity_case_map.py' % path.relative_to(ROOT))
    return 1 if args.check and stale else 0


if __name__ == '__main__':
    sys.exit(main())
