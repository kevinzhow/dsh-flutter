#!/usr/bin/env python3
"""Generate packages/dsh_i18n/lib/src/catalog.g.dart from dsh's client locale dictionaries.

  gen_catalog.py [--write]       re-extract (when the dsh checkout and node install exist), write the catalog
  gen_catalog.py --check         offline: committed IR -> catalog bytes compare + coverage check (fast)
  gen_catalog.py --check --full  also re-run the TypeScript extractor and compare the IR

Coverage: every en key must have a zh value and vice versa, and `{placeholder}` sets must
match, unless the gap is listed in tool/i18n/known-gaps.json. Stdlib only, any cwd.
Environment: same as tool/codegen/gen.py (DSH_SRC, DSH_CODEGEN_NODE_DIR, DSH_CODEGEN_NODE, DSH_CODEGEN_TMP, DART).
"""
from __future__ import annotations

import sys
sys.dont_write_bytecode = True
import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(REPO / "tool" / "codegen"))
import gen  # noqa: E402  (shared helpers: dsh_src, dart_bin, dart_format, sha, git_pin, scratch_parent)

CONFIG = HERE / "packages.json"
IR = HERE / "ir" / "locales.ir.json"
GAPS = HERE / "known-gaps.json"
OUT = "packages/dsh_i18n/lib/src/catalog.g.dart"
SYNC = REPO / "docs" / "upstream-sync.json"
PLACEHOLDER = re.compile(r"\{(\w+)\}")


def q(s: str) -> str:
    out = ["'"]
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == "'":
            out.append("\\'")
        elif ch == "$":
            out.append("\\$")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    out.append("'")
    return "".join(out)


def dump(obj: dict) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


def coverage(ir: dict) -> list[str]:
    """Problems not covered by known-gaps.json (plus stale gap entries)."""
    gaps = {(g["namespace"], g["key"], g["missing"]) for g in json.loads(GAPS.read_text())["gaps"]}
    seen: set[tuple[str, str, str]] = set()
    problems: list[str] = []
    for ns in ir["namespaces"]:
        for key, v in ns["entries"].items():
            found = []
            if v["zh"] is None:
                found.append("zh")
            if v["en"] is None:
                found.append("en")
            if v["en"] is not None and v["zh"] is not None \
                    and set(PLACEHOLDER.findall(v["en"])) != set(PLACEHOLDER.findall(v["zh"])):
                found.append("placeholders")
            for kind in found:
                t = (ns["namespace"], key, kind)
                seen.add(t)
                if t not in gaps:
                    problems.append(f"{ns['namespace']}.{key}: missing {kind}" if kind != "placeholders"
                                    else f"{ns['namespace']}.{key}: placeholders differ between en and zh")
    for t in sorted(gaps - seen):
        problems.append(f"known-gaps.json lists {t[0]}.{t[1]} ({t[2]}) but it is no longer a gap")
    return problems


def render(ir: dict, meta: dict) -> str:
    L = [
        "// GENERATED FILE. DO NOT EDIT.",
        "//",
        "// dsh client locale catalog (zh/en), flattened from the packages/client/*/src dictionaries.",
        "// Generated by tool/i18n/gen_catalog.py.",
        f"// Pinned dsh: {meta['repo']} commit {meta['commit']} ({meta.get('tag') or 'untagged'}, npm {meta['npmVersion']}).",
        "// Interpolation syntax of the sources: `{name}` placeholders only (see DshI18n).",
    ]
    for n in ir["noDictionary"]:
        L.append(f"// No dictionary: {n['package']} ({n['reason']}).")
    L += ["// To regenerate: python3 tool/i18n/gen_catalog.py --write", "", "// ignore_for_file: type=lint", "",
          "/// dsh namespace -> dsh package (relative to packages/) that owns its dictionary.",
          "const Map<String, String> dshCatalogPackages = {"]
    for ns in ir["namespaces"]:
        L.append(f"  {q(ns['namespace'])}: {q(ns['package'])},")
    L += ["};", "",
          "/// dsh namespace -> key -> en/zh text. `zh` is null only for a gap listed in",
          "/// tool/i18n/known-gaps.json.",
          "const Map<String, Map<String, ({String en, String? zh})>> dshCatalog = {"]
    for ns in ir["namespaces"]:
        L.append(f"  {q(ns['namespace'])}: {{")
        for key in sorted(ns["entries"]):
            v = ns["entries"][key]
            en = q(v["en"]) if v["en"] is not None else "''"
            zh = q(v["zh"]) if v["zh"] is not None else "null"
            L.append(f"    {q(key)}: (en: {en}, zh: {zh}),")
        L.append("  },")
    L += ["};", ""]
    return "\n".join(L)


def load_sync() -> dict | None:
    return json.loads(SYNC.read_text()) if SYNC.exists() else None


def extract(src: Path, out: Path) -> None:
    node = gen.os.environ.get("DSH_CODEGEN_NODE", str(Path.home() / ".local/opt/node24/bin/node"))
    nd = gen.node_dir()
    if not (nd / "node_modules" / "typescript").exists():
        raise SystemExit(f"typescript not installed under {nd}; see tool/codegen/extract/package.json")
    r = subprocess.run([node, str(HERE / "extract_locales.mjs"), "--dsh", str(src), "--node-dir", str(nd),
                        "--config", str(CONFIG), "--out", str(out)], capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit("locale extractor failed:\n" + r.stdout + r.stderr)


def sync_entry(src: Path | None, ir: dict, raw: str, formatted: str, old: dict | None) -> dict:
    if src is not None:
        inputs = gen.input_entries(src, ir["inputs"])
    else:
        inputs = next((g["inputs"] for g in (old or {}).get("generated", []) if g["output"] == OUT), [])
    return {
        "output": OUT,
        "generator": "tool/i18n/gen_catalog.py (tool/i18n/extract_locales.mjs)",
        "ir": str(IR.relative_to(REPO)),
        "irSha256": gen.sha_file(IR),
        "config": {"path": str(CONFIG.relative_to(REPO)), "sha256": gen.sha_file(CONFIG)},
        "knownGaps": {"path": str(GAPS.relative_to(REPO)), "sha256": gen.sha_file(GAPS)},
        "inputs": inputs,
        "rawSha256": gen.sha(raw.encode()),
        "outputSha256": gen.sha(formatted.encode()),
    }


def cmd_write(_: argparse.Namespace) -> int:
    src = gen.dsh_src()
    dart = gen.dart_bin()
    if dart is None:
        raise SystemExit("pinned dart not found; set DART")
    old = load_sync()
    if src is not None:
        tmp = Path(tempfile.mkdtemp(prefix="dsh-i18n-", dir=gen.scratch_parent()))
        try:
            extract(src, tmp / "locales.ir.json")
            ir = json.loads((tmp / "locales.ir.json").read_text())
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
        IR.parent.mkdir(parents=True, exist_ok=True)
        IR.write_text(dump(ir))
        pin = gen.git_pin(src)
        if old and old["dsh"]["commit"] == pin["commit"]:
            pin["pinnedAt"] = old["dsh"].get("pinnedAt", pin["pinnedAt"])
    else:
        if old is None:
            raise SystemExit("dsh checkout not found and no committed pin")
        ir = json.loads(IR.read_text())
        pin = old["dsh"]
    problems = coverage(ir)
    if problems:
        print("gen_catalog: coverage problems:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    raw = render(ir, pin)
    formatted = gen.dart_format(raw, dart)
    out = REPO / OUT
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(formatted)
    sync = old or {"schemaVersion": 1, "dsh": pin, "generated": []}
    sync["dsh"] = pin
    sync["generated"] = [g for g in sync["generated"] if g["output"] != OUT] + [sync_entry(src, ir, raw, formatted, old)]
    SYNC.write_text(dump(sync))
    keys = sum(len(n["entries"]) for n in ir["namespaces"])
    print(f"gen_catalog: wrote {OUT} ({len(ir['namespaces'])} namespaces, {keys} keys)")
    return 0


def cmd_check(args: argparse.Namespace) -> int:
    stale: list[str] = []
    sync = load_sync()
    entry = next((g for g in (sync or {}).get("generated", []) if g["output"] == OUT), None)
    if sync is None or entry is None:
        print("gen_catalog --check: STALE docs/upstream-sync.json has no entry for the catalog")
        return 1
    try:
        ir = json.loads(IR.read_text())
    except OSError:
        print("gen_catalog --check: STALE missing tool/i18n/ir/locales.ir.json")
        return 1
    if gen.sha_file(IR) != entry["irSha256"]:
        stale.append("tool/i18n/ir/locales.ir.json (sha differs from docs/upstream-sync.json)")
    for k, p in (("config", CONFIG), ("knownGaps", GAPS)):
        if gen.sha_file(p) != entry[k]["sha256"]:
            stale.append(f"{p.relative_to(REPO)} (changed since the catalog was generated)")
    problems = coverage(ir)
    raw = render(ir, sync["dsh"])
    dart = gen.dart_bin()
    out = REPO / OUT
    if dart is not None and not args.no_format:
        text = gen.dart_format(raw, dart)
        if not out.exists() or out.read_text() != text:
            stale.append(OUT + " (differs from regeneration)")
    else:
        if gen.sha(raw.encode()) != entry["rawSha256"]:
            stale.append(OUT + " (emitter output differs from recorded rawSha256)")
        if not out.exists() or gen.sha_file(out) != entry["outputSha256"]:
            stale.append(OUT + " (committed file differs from recorded outputSha256)")
    src = gen.dsh_src()
    notes = ""
    if src is not None:
        head = subprocess.run(["git", "-C", str(src), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
        if head == sync["dsh"]["commit"]:
            for i in entry["inputs"]:
                f = src / i["path"]
                if not f.exists() or gen.sha_file(f) != i["sha256"]:
                    stale.append(f"{i['path']} (input changed, rerun gen_catalog.py --write)")
        else:
            notes = " (dsh checkout at another commit, inputs not compared)"
    else:
        notes = " (no dsh checkout, inputs not compared)"
    if args.full:
        if src is None:
            print("gen_catalog --check --full: needs a dsh checkout (DSH_SRC)")
            return 2
        tmp = Path(tempfile.mkdtemp(prefix="dsh-i18n-full-", dir=gen.scratch_parent()))
        try:
            extract(src, tmp / "locales.ir.json")
            if (tmp / "locales.ir.json").read_text() != IR.read_text():
                stale.append("tool/i18n/ir/locales.ir.json (re-extraction differs)")
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
    if stale or problems:
        msg = []
        if stale:
            msg.append("STALE " + "; ".join(stale))
        if problems:
            msg.append(f"COVERAGE {len(problems)} problem(s): " + "; ".join(problems[:10]))
        print("gen_catalog --check: " + " | ".join(msg))
        return 1
    keys = sum(len(n["entries"]) for n in ir["namespaces"])
    print(f"gen_catalog --check: OK {len(ir['namespaces'])} namespaces, {keys} keys, full zh coverage{notes}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    ap.add_argument("--full", action="store_true")
    ap.add_argument("--no-format", action="store_true")
    args = ap.parse_args()
    return cmd_check(args) if args.check else cmd_write(args)


if __name__ == "__main__":
    sys.exit(main())
