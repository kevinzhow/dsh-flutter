"""What a tool/parity-ext/build-*.py builder imports (it runs with this directory as sys.path[0]).

    from builders_api import base_case, replace_cases, themed

`replace_cases(prefix, cases)` replaces every case whose id starts with `prefix` in the run-time
manifest ($PARITY_EXT_MANIFEST, generated by tool/parity-ext/run and never committed) and appends the new
ones, so a builder is idempotent and never touches another builder's cases.
"""
import copy
import json
import os
import pathlib
import sys

THEMES = ('light', 'dark')
SELECTOR = '[data-parity-target]'


def manifest_path():
    value = os.environ.get('PARITY_EXT_MANIFEST')
    if not value:
        sys.exit('PARITY_EXT_MANIFEST is not set: builders run through `tool/parity-ext/run`, which generates the manifest')
    return pathlib.Path(value)


def themed(template, themes=THEMES):
    """One case per theme from a template whose `id` is the id WITHOUT the theme suffix."""
    out = []
    for theme in themes:
        case = copy.deepcopy(template)
        case['id'] = '%s.%s' % (template['id'], theme)
        case['title'] = '%s (%s)' % (template['title'], theme)
        case['theme'] = theme
        out.append(case)
    return out


def base_case(case_id, title, kind, viewport, variants, *, locale='en', category='extension', react_hint='', flutter_hint='',
              regions=None):
    """A case template (pass through `themed`). `variants` is [(id, name, props, interactions)]."""
    case = {
        'id': case_id, 'title': title, 'kind': kind, 'surface': case_id.split('.')[2], 'category': category,
        'suite': 'dsh-flutter-extension', 'viewport': viewport, 'locale': locale,
        'variants': [{'id': v, 'name': n, 'props': p, **({'interactions': i} if i else {})} for v, n, p, i in variants],
        'capture': {'selector': SELECTOR, 'flutterKey': 'parity-target', 'crop': 'element'},
        'tolerance': {'pixelRatio': 0.02, 'layoutPx': 1},
    }
    if react_hint:
        case['reactPathHint'] = react_hint
    if flutter_hint:
        case['flutterCaseHint'] = flutter_hint
    if regions:
        case['regions'] = regions
    return case


def replace_cases(prefix, cases):
    path = manifest_path()
    manifest = json.loads(path.read_text())
    manifest['cases'] = [c for c in manifest['cases'] if not c['id'].startswith(prefix)] + cases
    path.write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + '\n')
    print('%d cases for %s* (%d total)' % (len(cases), prefix, len(manifest['cases'])))
