// dsh's attachment surfaces (ui-attachment, ui-chat), the real components with fixture state:
//
//   attachment.chip     FileCard: one pending-file card per item (ui-attachment FileCard.tsx)
//   attachment.draft    ComposerAttachments: the composer's draft rail of 64px image thumbnails and file cards
//                       (client/ComposerAttachments.tsx over AttachmentRail.tsx)
//   attachment.sent     UserContent's file cards of a sent message (ui-chat UserContent.tsx, MessageItem.module.css
//                       fileCard / fileIcon / fileContent / fileName / fileMeta)
//   attachment.gallery  ImageGallery: single / tile / thumbnail variants with loaded, loading and failed images
//                       (ui-attachment MessageImage.tsx)
//
// Host services mocked: the conversation locale seat `t` (a translator over the real dictionaries, mocks/locale.ts), the
// authorized image loader of the gallery (`load`, with `load.peek` answering synchronously for loaded images; a loader
// that never settles is the loading state and a rejecting one the failed state) and the composer callbacks (no-ops).
// Images are synthetic PNGs generated by the builder (tool/parity-ext/synthetic_images.py) and shipped in the props.
import { useLayoutEffect, useMemo, useRef } from 'react'
import { en, zh } from '@dsh/ui-conversation/src/client/locales.ts'
import { FileCard } from '@dsh/ui-attachment/src/FileCard.tsx'
import { ImageGallery } from '@dsh/ui-attachment/src/MessageImage.tsx'
import { ComposerAttachments } from '@dsh/ui-attachment/src/client/ComposerAttachments.tsx'
import { fileCardLabels, messageImageLabels } from '@dsh/ui-attachment/src/client/labels.ts'
import { UserContent } from '@dsh/ui-chat/src/client/chat/UserContent.tsx'
import { Stack } from '../../parity-web/host/layout.tsx'
import { createTranslator } from '../../parity-web/host/mocks/locale.ts'
import type { KindRenderer } from '../../parity-web/host/types.ts'
import { imagesDecoded, publishSettle, tagChild } from './settle.ts'

const noop = () => {}
const dataUrl = (base64: string) => `data:image/png;base64,${base64}`

/** Renders `children` and tags the first element of the wrapper subtree matching `selector` (or its first child). */
function Tagged({ id, selector, children }: { id: string; selector?: string; children: React.ReactNode }) {
  const ref = useRef<HTMLDivElement>(null)
  useLayoutEffect(() => {
    const host = ref.current
    tagChild(selector === undefined ? host?.firstElementChild ?? null : host?.querySelector(selector) ?? null, id)
  })
  // display: contents keeps the wrapper out of layout: the real component stays a direct flex item of the case's stack.
  return <div ref={ref} style={{ display: 'contents' }}>{children}</div>
}

interface ChipItem { id: string; name: string; bytes: number; state: 'ready' | 'uploading' | 'error'; progress?: number }

interface DraftItem extends ChipItem { kind: 'image' | 'file'; image?: string }

/** The `uploads` record of ComposerAttachments for the file items of a rail. */
function uploadsOf(items: DraftItem[]) {
  const uploads: Record<string, { status: string; loaded?: number; total?: number }> = {}
  for (const item of items) {
    if (item.kind !== 'file') continue
    uploads[item.id] = item.state === 'error'
      ? { status: 'failed' }
      : item.state === 'ready'
        ? { status: 'ready' }
        : item.progress === undefined ? { status: 'uploading' } : { status: 'uploading', loaded: item.progress * 1000, total: 1000 }
  }
  return uploads
}

interface GalleryItem { id: string; image: string; state: 'loaded' | 'loading' | 'failed'; name?: string }
interface GalleryProps {
  id: string; align: 'start' | 'end'; thumbnail?: boolean; compact?: boolean; items: GalleryItem[]
}

function Gallery({ gallery, images, t }: {
  gallery: GalleryProps
  images: Record<string, { base64: string; width: number; height: number }>
  t: ReturnType<typeof createTranslator>
}) {
  const ref = useRef<HTMLDivElement>(null)
  const { specs, load } = useMemo(() => {
    const byId = new Map(gallery.items.map((item) => [item.id, item]))
    const specs = gallery.items.map((item) => {
      const source = images[item.image]
      return {
        attachment: {
          attachmentId: item.id, mediaType: 'image/png', bytes: 1, width: source.width, height: source.height,
          ...item.name === undefined ? {} : { name: item.name },
        },
      }
    })
    const loader = ((attachment: { attachmentId: string }) => {
      const item = byId.get(attachment.attachmentId)!
      if (item.state === 'failed') return Promise.reject(new Error('parity: load failed'))
      if (item.state === 'loading') return new Promise<string>(() => {})
      return Promise.resolve(dataUrl(images[item.image].base64))
    }) as any
    loader.peek = (attachment: { attachmentId: string }) => {
      const item = byId.get(attachment.attachmentId)!
      return item.state === 'loaded' ? dataUrl(images[item.image].base64) : undefined
    }
    return { specs, load: loader }
  }, [gallery, images])
  // parity ids: <gallery>-<item id> on every frame button, in order (frames and error buttons alike).
  useLayoutEffect(() => {
    ref.current?.querySelectorAll('button[data-variant]').forEach((button, index) => {
      tagChild(button, `${gallery.id}-${gallery.items[index]?.id ?? index}`)
    })
  })
  return (
    <div ref={ref} style={{ display: 'contents' }}>
      <ImageGallery
        images={specs as any}
        load={load}
        align={gallery.align}
        compact={gallery.compact === true}
        thumbnail={gallery.thumbnail === true}
        labels={messageImageLabels(t as any)}
      />
    </div>
  )
}

export const kinds: Record<string, KindRenderer> = {
  /** props {layout, items: ChipItem[]}; parity id: the item id (the card). */
  'attachment.chip': (props, ctx) => {
    const t = createTranslator(ctx.case.locale, { en, zh })
    return (
      <Stack layout={props.layout}>
        {(props.items as ChipItem[]).map((item) => (
          <Tagged key={item.id} id={item.id}>
            <FileCard
              name={item.name}
              bytes={item.bytes}
              state={item.state}
              {...item.progress === undefined ? {} : { progress: item.progress }}
              labels={fileCardLabels(t as any, item.name)}
              onRemove={noop}
              onRetry={noop}
            />
          </Tagged>
        ))}
      </Stack>
    )
  },
  /**
   * props {layout, images: {key: base64}, rails: [{items: DraftItem[]}]}: one ComposerAttachments per rail.
   * parity ids: the item id on each rail item (the card or the 64px image box).
   */
  'attachment.draft': (props, ctx) => {
    const t = createTranslator(ctx.case.locale, { en, zh })
    const images = props.images as Record<string, string>
    publishSettle(imagesDecoded, 'draft thumbnails decoded')
    return (
      <Stack layout={props.layout}>
        {(props.rails as { items: DraftItem[] }[]).map((rail, index) => (
          <Rail key={index} items={rail.items} images={images} t={t} />
        ))}
      </Stack>
    )
  },
  /** props {layout, files: [{name, bytes}]}: the real UserContent with file attachments only (no bubble). */
  'attachment.sent': (props, ctx) => {
    const t = createTranslator(ctx.case.locale, { en, zh })
    const content = {
      text: '',
      extraBlocks: [],
      attachments: (props.files as { name: string; bytes: number }[]).map((file) => ({ type: 'file', file })),
    }
    const ref = (el: HTMLDivElement | null) => {
      el?.querySelectorAll('[data-message-attachments] > span').forEach((card, index) => tagChild(card, `sent-${index}`))
    }
    return (
      <Stack layout={props.layout}>
        <div ref={ref} style={{ display: 'contents' }}>
          <UserContent
            {...{
              content, loadImage: noop, facts: undefined, t,
              renderSlot: () => null, renderFactorySlot: () => null,
            } as any}
          />
        </div>
      </Stack>
    )
  },
  /**
   * props {layout, images: {key: {base64, width, height}}, galleries: GalleryProps[]}: one ImageGallery each; parity ids
   * `<gallery id>-<item id>`.
   */
  'attachment.gallery': (props, ctx) => {
    const t = createTranslator(ctx.case.locale, { en, zh })
    publishSettle(imagesDecoded, 'gallery images decoded')
    return (
      <Stack layout={props.layout}>
        {(props.galleries as GalleryProps[]).map((gallery) => (
          <Gallery key={gallery.id} gallery={gallery} images={props.images} t={t} />
        ))}
      </Stack>
    )
  },
}

function Rail({ items, images, t }: { items: DraftItem[]; images: Record<string, string>; t: ReturnType<typeof createTranslator> }) {
  const ref = useRef<HTMLDivElement>(null)
  const attachments = useMemo(() => items.map((item) => item.kind === 'image'
    ? { id: item.id, kind: 'image', file: { name: item.name, size: item.bytes }, previewUrl: dataUrl(images[item.image!]) }
    : { id: item.id, kind: 'file', file: { name: item.name, size: item.bytes } }), [items, images])
  const uploads = useMemo(() => uploadsOf(items), [items])
  useLayoutEffect(() => {
    // The rail's items are the direct children of the `group` element, in draft order.
    ref.current?.querySelectorAll('[role="group"] > div').forEach((item, index) => tagChild(item, items[index].id))
  })
  return (
    <div ref={ref} style={{ display: 'contents' }}>
      <ComposerAttachments
        {...{
          attachments, canAcceptDrop: true, onAddFiles: noop, onRemoveAttachment: noop, uploads, onRetryFile: noop,
          dropLimits: undefined, t,
        } as any}
      />
    </div>
  )
}
