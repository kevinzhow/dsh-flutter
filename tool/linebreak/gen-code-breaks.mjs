// Measures where Chromium may break a line of preformatted code (CSS `white-space: pre-wrap`, `overflow-wrap: normal`)
// between two printable ASCII characters, and writes packages/dsh_ui/lib/src/dsh_code_breaks.g.dart.
//
// Flutter breaks lines with the ICU rules of its own engine build; Chromium's differ in the details that matter for
// source code (it may break after the space in `{ name`, it does not break between `}` and a backtick). The table
// lets the code surfaces tell Flutter's breaker exactly where Chromium would: a zero-width space where a break is
// allowed, a word joiner where it is not (dsh_code_highlight.dart: dshWrapBreaks).
//
//   node gen-code-breaks.mjs --deps <dir with node_modules/playwright-core> --browsers <ms-playwright cache> --out <file>
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'

const args = Object.fromEntries(process.argv.slice(2).reduce((acc, a, i, all) => {
  if (a.startsWith('--')) acc.push([a.slice(2), all[i + 1]])
  return acc
}, []))
process.env.PLAYWRIGHT_BROWSERS_PATH = args.browsers ?? process.env.PLAYWRIGHT_BROWSERS_PATH
const require = createRequire(path.join(path.resolve(args.deps), 'node_modules', 'x.js'))
const { chromium } = require('playwright-core')
const browser = await chromium.launch()
const page = await browser.newPage()
const chars = []
for (let c = 0x20; c < 0x7f; c++) chars.push(String.fromCharCode(c))
await page.setContent('<body style="margin:0"></body>')
const rows = await page.evaluate((chars) => {
  const style = 'font:20px/24px monospace;white-space:pre-wrap;overflow-wrap:normal;word-break:normal;width:1.5ch;position:absolute;left:0;top:0'
  const out = []
  for (const a of chars) {
    let row = ''
    for (const b of chars) {
      // The pair sits between two letters so the contexts around it are those of source code: `x` `a` `b` `x`.
      const el = document.createElement('div')
      el.setAttribute('style', style)
      el.textContent = `x${a}${b}x`
      document.body.appendChild(el)
      const range = document.createRange()
      const node = el.firstChild
      range.setStart(node, 2); range.setEnd(node, 3)
      const first = document.createRange(); first.setStart(node, 1); first.setEnd(node, 2)
      const second = range.getClientRects()[0], before = first.getClientRects()[0]
      // A break between a and b puts b on a later line than a (a trailing space has no box of its own when it hangs).
      const broke = second && before ? second.top > before.top + 1 : false
      row += broke ? '1' : '0'
      el.remove()
    }
    out.push(row)
  }
  return out
}, chars)
await browser.close()
const dart = `// GENERATED by tool/linebreak/gen-code-breaks.mjs from Chromium ${'(see the script)'}; do not edit.
// Row = the character before a possible break, column = the character after (printable ASCII, U+0020..U+007E, in order):
// '1' where Chromium's line breaker (pre-wrap, overflow-wrap: normal) may break between them, '0' where it may not.
const List<String> dshCodeBreakTable = [
${rows.map((r) => `  '${r}',`).join('\n')}
];
`
fs.writeFileSync(args.out, dart)
console.log('wrote', args.out, rows.filter((r) => r.includes('1')).length, 'rows with breaks')
