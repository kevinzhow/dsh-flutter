#!/usr/bin/env python3
"""Generate packages/dsh_ui/lib/src/charcoal_icons.g.dart: the Charcoal V2 glyphs of Whalee's own UI.

Icon rule (docs/parity.md): a glyph dsh web draws is dsh's (dsh_icons.g.dart, dsh_shell_icons.g.dart); a control only
Whalee has (the phone top bar's menu, pairing, the QR scanner, certificate prompts, the attach sheet) uses Charcoal V2,
never a Material or Cupertino glyph. The SVG sources are vendored in tool/icons/charcoal/ (24px regular set of
https://github.com/kevinzhow/charcoal-flutter, packages/charcoal_icons, commit de89016ed5ed8b2054ff782d4ddd38cc5ca3847, from
pixiv/charcoal; Apache-2.0, see tool/icons/charcoal/LICENSE and NOTICE and THIRD_PARTY_NOTICES.md). The generator reads
only that directory, so it needs no checkout.

    gen_charcoal_icons.py [--check]
"""
import importlib.util
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('gen_icons', HERE / 'gen_icons.py')
g = importlib.util.module_from_spec(spec)
spec.loader.exec_module(g)

SRC = HERE / 'charcoal'
OUT = g.ROOT / 'packages' / 'dsh_ui' / 'lib' / 'src' / 'charcoal_icons.g.dart'

# Charcoal icon file -> Dart identifier, with where Whalee uses it.
ICONS = {
    'list': 'list',  # phone top bar: opens the drawer
    'sliders': 'sliders',  # pairing page: the app settings entry
    'lock': 'lock',  # connection security chip, pinned certificate
    'warn.triangle': 'warning',  # plain http notice, certificate warning
    'arrow.left': 'arrowLeft',  # pairing page back
    'paste': 'paste',  # paste launch link
    'view.fit': 'scan',  # scan a QR code
    'images': 'images',  # attach sheet: photo library
    'camera': 'camera',  # attach sheet: camera
    'file': 'file',  # attach sheet: files
    'x': 'close',  # QR scanner close
}


def build():
    lines = [
        '// GENERATED by tool/icons/gen_charcoal_icons.py from tool/icons/charcoal (Charcoal V2, Apache-2.0). Do not edit.',
        '// ignore_for_file: lines_longer_than_80_chars',
        '',
        "import 'dsh_icon_data.dart';",
        '',
        "/// Charcoal V2 glyphs (24px regular) for the controls only Whalee has; dsh's own glyphs are in `DshIcons`.",
        'abstract final class CharcoalIcons {',
    ]
    for name, ident in ICONS.items():
        text = (SRC / (name + '.svg')).read_text()
        els = re.findall(r'<path\b([^>]*)/>', text)
        if not els or re.search(r'<(circle|rect|line|polygon|g)\b', text):
            sys.exit('gen_charcoal_icons: %s must be plain paths' % name)
        lines.append('  /// Charcoal `%s`.' % name)
        lines.append('  static const %s = DshIconData(' % ident)
        lines.append('    viewBox: 24,')
        lines.append('    size: 24,')
        lines.append('    strokeWidth: 1.0,')
        lines.append('    shapes: [')
        for attrs in els:
            d = re.search(r'\bd="([^"]+)"', attrs).group(1)
            even = 'fill-rule="evenodd"' in attrs
            lines.append("      DshIconShape('%s', fill: true, evenOdd: %s)," % (d, str(even).lower()))
        lines.append('    ],')
        lines.append('  );')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main():
    text = g.formatted(build())
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print('gen_charcoal_icons: %s is stale; run tool/icons/gen_charcoal_icons.py' % OUT.relative_to(g.ROOT), file=sys.stderr)
            sys.exit(1)
        print('gen_charcoal_icons: up to date')
        return
    OUT.write_text(text)
    print('gen_charcoal_icons: wrote %s (%d icons)' % (OUT.relative_to(g.ROOT), len(ICONS)))


if __name__ == '__main__':
    main()
