#!/usr/bin/env python3
"""Generate packages/dsh_ui/lib/src/dsh_code_language.g.dart from dsh's language tables.

Two tables decide the language label of a code card: the file-extension table of `@deepseek-ai/dsh-util-code-language`
(`languageForPath`) and the highlighter's alias table in ui-primitives (`supportsHighlighting`). Both are read from the
pinned dsh checkout.

    gen_code_language.py [--check]
"""
import os
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / 'packages' / 'dsh_ui' / 'lib' / 'src' / 'dsh_code_language.g.dart'
SRC = pathlib.Path(os.environ.get('DSH_SRC', str(ROOT / '.local' / 'dsh-src')))
EXT_FILE = SRC / 'packages' / 'util' / 'code-language' / 'src' / 'index.ts'
ALIAS_FILE = SRC / 'packages' / 'client' / 'ui-primitives' / 'src' / 'markdown' / 'highlight.ts'


def build():
    ext_text = EXT_FILE.read_text()
    block = re.search(r'const LANGUAGE_EXTENSIONS[^=]*=\s*\{([\s\S]*?)\n\}', ext_text).group(1)
    extensions = {}
    for m in re.finditer(r"^\s*('?[\w-]+'?):\s*\[([^\]]*)\]", block, re.M):
        language = m.group(1).strip("'")
        for ext in re.findall(r"'([^']+)'", m.group(2)):
            extensions[ext] = language
    alias_text = ALIAS_FILE.read_text()
    block = re.search(r'const LANG_ALIASES = new Map<string, string>\(\[([\s\S]*?)\n\]\)', alias_text).group(1)
    aliases = dict(re.findall(r"\['([^']+)', '([^']+)'\]", block))
    if not extensions or not aliases:
        sys.exit('gen_code_language: tables not found')
    lines = [
        '// GENERATED by tool/icons/gen_code_language.py from dsh util/code-language and ui-primitives. Do not edit.',
        '',
        '/// Lower-case file extension to canonical language id (`languageForPath`).',
        'const Map<String, String> dshLanguageByExtension = {',
    ]
    lines += ["  '%s': '%s'," % (k, v) for k, v in sorted(extensions.items())]
    lines += ['};', '', '/// Language hint to grammar id (`supportsHighlighting`).', 'const Map<String, String> dshGrammarByHint = {']
    lines += ["  '%s': '%s'," % (k, v) for k, v in sorted(aliases.items())]
    lines += ['};', '']
    return '\n'.join(lines)


def main():
    if not EXT_FILE.exists():
        print('gen_code_language: tool unavailable: no dsh checkout at %s' % SRC, file=sys.stderr)
        sys.exit(2)
    text = build()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print('gen_code_language: %s is stale; run tool/icons/gen_code_language.py' % OUT.relative_to(ROOT), file=sys.stderr)
            sys.exit(1)
        print('gen_code_language: up to date')
        return
    OUT.write_text(text)
    print('gen_code_language: wrote %s' % OUT.relative_to(ROOT))


main()
