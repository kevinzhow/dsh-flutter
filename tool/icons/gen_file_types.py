#!/usr/bin/env python3
"""Generate packages/dsh_ui/lib/src/dsh_file_types.g.dart from dsh's file-type artwork and classifier.

dsh's file cards draw `FileTypeIcon` (ui-primitives/src/FileTypeIcon.tsx): a page with a folded corner and a category mark
on a 28 unit grid, and classify a path by its name and extension (FileTypeIcon.tsx + code-file-types.ts). This script reads
both from the pinned dsh checkout and writes the path data and the tables.

Not ported: the full-colour per-language code artwork (`CodeFileIcon`, 48 SVG documents with gradients); every detailed
code type draws the generic `code` glyph here.

    gen_file_types.py [--check]
"""
import os
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / 'packages' / 'dsh_ui' / 'lib' / 'src' / 'dsh_file_types.g.dart'
SRC = pathlib.Path(os.environ.get('DSH_SRC', str(ROOT / '.local' / 'dsh-src')))
PRIM = SRC / 'packages' / 'client' / 'ui-primitives' / 'src'
ICON = PRIM / 'FileTypeIcon.tsx'
CODE = PRIM / 'code-file-types.ts'
CSS = PRIM / 'FileTypeIcon.module.css'

# marks that carry a transform in dsh: name of the constant -> scale about (14, 16)
TRANSFORMS = {'FILE_MARK_TRANSFORM': 1.12, 'LARGE_FILE_MARK_TRANSFORM': 1.22}


def const_string(text, name):
    m = re.search(r"const %s = '([^']+)'" % name, text)
    if not m:
        sys.exit('gen_file_types: const %s not found' % name)
    return m.group(1)


def shapes_of(block):
    out = []
    for m in re.finditer(r'<path\b([\s\S]*?)/>', block):
        attrs = m.group(1)
        d = re.search(r'\bd="([^"]+)"', attrs).group(1)
        d = re.sub(r'\s+', ' ', d).strip()
        stroke = re.search(r'strokeWidth="([\d.]+)"', attrs)
        out.append((d, float(stroke.group(1)) if stroke and 'stroke="currentColor"' in attrs else None,
                    'evenodd' in attrs))
    return out


def glyphs(text):
    body = text[text.index('function glyph('):text.index('/** Closed-union exhaustiveness guard')]
    out = {}
    for m in re.finditer(r"case '(\w+)':([\s\S]*?)(?=\n    case '|\n    /\* v8)", body):
        kind, seg = m.group(1), m.group(2)
        if kind == 'other':
            out[kind] = {'scale': None, 'muted': True, 'shapes': []}
            continue
        if kind == 'excel':
            sheet = text[text.index('function SpreadsheetGlyph'):text.index('function glyph(')]
            out[kind] = {'scale': None, 'muted': False, 'shapes': shapes_of(sheet)}
            continue
        if kind == 'folder':
            continue
        t = re.search(r'markTransform=\{(\w+)\}', seg)
        out[kind] = {'scale': TRANSFORMS[t.group(1)] if t else None, 'muted': False, 'shapes': shapes_of(seg)}
    return out


def folder(text):
    seg = text[text.index('function FolderGlyph'):text.index('function SpreadsheetGlyph')]
    d = re.sub(r'\s+', ' ', re.search(r'<path\s+d="([^"]+)"', seg).group(1)).strip()
    mark = re.search(r'<path d="([^"]+)" stroke="currentColor" strokeWidth="([\d.]+)"', seg)
    ty = re.search(r'FOLDER_MARK_TRANSFORM = \'translate\(14 ([\d.]+)\) scale\(([\d.]+)\)', text)
    return d, mark.group(1), float(mark.group(2)), float(ty.group(1)), float(ty.group(2))


def table(text, name):
    block = re.search(r'const %s[^=]*=\s*\{([\s\S]*?)\n\}' % name, text).group(1)
    return {(a or b): c for a, b, c in re.findall(r"^\s*(?:'([^']+)'|(\w+)):\s*'([^']+)'", block, re.M)}


def pairs(text, name):
    block = re.search(r'const %s[^=]*=\s*\[([\s\S]*?)\n\]' % name, text).group(1)
    return re.findall(r"\['([^']+)', '([^']+)'\]", block)


def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"


def build():
    icon = ICON.read_text()
    code = CODE.read_text()
    body = const_string(icon, 'FILE_BODY')
    fold = const_string(icon, 'FILE_FOLD')
    g = glyphs(icon)
    fd, fm, fw, fy, fs = folder(icon)
    ext = table(icon, 'EXTENSION_TYPES')
    names = table(icon, 'NAME_TYPES')
    code_names = table(code, 'FILE_NAME_TYPES')
    code_ext = table(code, 'EXTENSION_TYPES')
    prefixes = pairs(code, 'FILE_NAME_PREFIX_TYPES')
    suffixes = pairs(code, 'FILE_NAME_SUFFIX_TYPES')
    link = re.findall(r"'(\w+)'", re.search(r'const LINK_CODE_EXTENSIONS = new Set\(\[([\s\S]*?)\]\)', code).group(1))
    if not (g and ext and code_ext):
        sys.exit('gen_file_types: tables not found')
    violet = re.search(r'--dsh-file-type-violet:\s*rgb\((\d+),\s*(\d+),\s*(\d+)\)', CSS.read_text())
    if not violet:
        sys.exit('gen_file_types: violet not found in FileTypeIcon.module.css')
    argb = 0xFF000000 | (int(violet.group(1)) << 16) | (int(violet.group(2)) << 8) | int(violet.group(3))
    L = ['// GENERATED by tool/icons/gen_file_types.py from dsh ui-primitives FileTypeIcon and code-file-types. Do not edit.',
         '// ignore_for_file: lines_longer_than_80_chars', '',
         "import 'dsh_file_types.dart';", '',
         '/// `--dsh-file-type-violet` of FileTypeIcon.module.css (image and video glyphs): the design platform has no token for it.',
         'const int dshFileTypeViolet = 0x%08X;' % argb,
         '/// The page and its folded corner, on dsh\'s 28 unit grid.',
         'const String dshFileBodyPath = %s;' % q(body),
         'const String dshFileFoldPath = %s;' % q(fold),
         '/// The folder glyph and its mark.',
         'const DshFolderGlyph dshFolderGlyph = DshFolderGlyph(%s, %s, %s, %s, %s);' % (q(fd), q(fm), fw, fy, fs),
         '', '/// Category mark per glyph kind.', 'const Map<String, DshFileGlyph> dshFileGlyphs = {']
    for kind, v in g.items():
        shapes = ', '.join("DshGlyphShape(%s, strokeWidth: %s, evenOdd: %s)" % (q(d), w if w is not None else 'null', str(eo).lower())
                           for d, w, eo in v['shapes'])
        L.append("  '%s': DshFileGlyph(markScale: %s, muted: %s, shapes: [%s])," % (
            kind, v['scale'] if v['scale'] is not None else 'null', str(v['muted']).lower(), shapes))
    L += ['};', '', '/// Extension (lower case) to glyph kind (`EXTENSION_TYPES` of FileTypeIcon).',
          'const Map<String, String> dshFileTypeByExtension = {']
    L += ["  '%s': '%s'," % kv for kv in sorted(ext.items())]
    L += ['};', '', '/// Whole lower-case name to glyph kind (`NAME_TYPES`).', 'const Map<String, String> dshFileTypeByName = {']
    L += ["  '%s': '%s'," % kv for kv in sorted(names.items())]
    L += ['};', '', '/// Names, prefixes, suffixes and extensions that dsh gives a detailed code icon (all draw the code glyph here).',
          'const Set<String> dshCodeFileNames = {']
    L += ["  '%s'," % k for k in sorted(code_names)]
    L += ['};', 'const List<String> dshCodeFileNamePrefixes = [']
    L += ["  '%s'," % p for p, _ in prefixes]
    L += ['];', 'const List<String> dshCodeFileNameSuffixes = [']
    L += ["  '%s'," % s for s, _ in suffixes]
    L += ['];', 'const Set<String> dshCodeFileExtensions = {']
    L += ["  '%s'," % k for k in sorted(code_ext)]
    L += ['};', '', '/// Extensions that keep the coarse code glyph in clickable links (`LINK_CODE_EXTENSIONS`).',
          'const Set<String> dshLinkCodeExtensions = {']
    L += ["  '%s'," % k for k in sorted(set(link))]
    L += ['};', '']
    return '\n'.join(L)


def formatted(text):
    import subprocess
    import tempfile
    with tempfile.TemporaryDirectory() as tmp:
        path = pathlib.Path(tmp) / 'gen.dart'
        path.write_text(text)
        subprocess.run(['dart', 'format', str(path)], check=True, capture_output=True)
        return path.read_text()


def main():
    if not ICON.exists():
        print('gen_file_types: tool unavailable: no dsh checkout at %s' % SRC, file=sys.stderr)
        sys.exit(2)
    text = formatted(build())
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print('gen_file_types: %s is stale; run tool/icons/gen_file_types.py' % OUT.relative_to(ROOT), file=sys.stderr)
            sys.exit(1)
        print('gen_file_types: up to date')
        return
    OUT.write_text(text)
    print('gen_file_types: wrote %s' % OUT.relative_to(ROOT))


main()
